import com.example.core.format.FormatRegistry
import com.example.core.format.Support

/** Prints the format matrix as Markdown so docs/FILE_FORMATS.md is generated from the registry, never hand-edited. */
fun main() {
    val all = FormatRegistry.all
    fun count(s: Support) = all.filter { it.support == s }.sumOf { it.extensions.size }
    println("<!-- GENERATED by tools/GenFormatDocs.kt from FormatRegistry. Do not edit by hand. -->")
    println()
    println("**${FormatRegistry.extensionCount} extensions across ${all.size} format groups:** " +
        "${count(Support.FULL)} fully supported, ${count(Support.PARTIAL)} partial, ${count(Support.IDENTIFY)} identified only.")
    println()
    for (kind in all.map { it.kind }.distinct()) {
        println("### ${kind.name}")
        println()
        println("| Format | Support | Extensions |")
        println("|---|---|---|")
        for (s in all.filter { it.kind == kind }) {
            val sup = when (s.support) { Support.FULL -> "✅ full"; Support.PARTIAL -> "🔄 partial"; Support.IDENTIFY -> "⏳ identify only" }
            println("| ${s.displayName} | $sup | ${s.extensions.joinToString(", ") { "`$it`" }} |")
        }
        println()
    }
}
